// build.mjs — renders a catalog.json into a static page plus its text route.
// Zero dependencies, node >= 22.
//
//   node build.mjs [--root DIR] [--site DIR] [--schema FILE] [--generator NAME]
//                  [--check] [--no-validate] [--help]
//
// The defaults are the room's layout: --root is the current directory, --site is
// <root>/site, assets come from <site>/src and output goes to <site>/index.html
// plus <root>/catalog.md. --generator defaults to "site/build.mjs" so the room's
// output stays byte-identical.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const slash = (p) => p.split("\\").join("/");

const USAGE = `usage: node ${slash(relative(process.cwd(), here))}/build.mjs [options]

  --root DIR        directory holding catalog.json (default: cwd)
  --site DIR        directory holding src/ and index.html (default: <root>/site)
  --schema FILE     JSON Schema for the catalog (default: <site>/catalog.schema.json)
  --generator NAME  name written into the "generated by" notes
                    (default: site/build.mjs, matching the room)
  --check           do not write; exit non-zero if the committed output is stale
  --no-validate     skip catalog schema validation
  --help            print this message`;

const readOrNull = (path) => {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
};

function parseArgs(argv) {
  const options = { root: process.cwd(), generator: "site/build.mjs" };
  for (let i = 0; i < argv.length; i++) {
    switch (argv[i]) {
      case "--root": options.root = argv[++i]; break;
      case "--site": options.site = argv[++i]; break;
      case "--schema": options.schema = argv[++i]; break;
      case "--generator": options.generator = argv[++i]; break;
      case "--check": options.check = true; break;
      case "--no-validate": options.noValidate = true; break;
      case "--help":
      case "-h": options.help = true; break;
      default:
        console.error(`unknown option: ${argv[i]}`);
        console.error(USAGE);
        process.exit(2);
    }
  }
  return options;
}

const isObject = (value) => typeof value === "object" && value !== null && !Array.isArray(value);

function typeName(value) {
  if (value === null) return "null";
  if (Array.isArray(value)) return "array";
  return typeof value;
}

function matchesType(value, type) {
  switch (type) {
    case "object": return isObject(value);
    case "array": return Array.isArray(value);
    case "string": return typeof value === "string";
    case "number": return typeof value === "number" && Number.isFinite(value);
    case "integer": return Number.isInteger(value);
    case "boolean": return typeof value === "boolean";
    case "null": return value === null;
    default: return true;
  }
}

// walk covers the JSON Schema subset the room's schema actually uses: type,
// required, properties, items, enum and pattern. Other keywords are ignored
// rather than guessed at.
function walk(value, schema, path, errors) {
  if (!isObject(schema)) return;
  if (schema.type !== undefined) {
    const types = Array.isArray(schema.type) ? schema.type : [schema.type];
    if (!types.some((type) => matchesType(value, type))) {
      errors.push(`${path}: expected ${types.join(" or ")}, got ${typeName(value)}`);
      return;
    }
  }
  if (Array.isArray(schema.enum) && !schema.enum.includes(value)) {
    errors.push(`${path}: ${JSON.stringify(value)} is not one of ${schema.enum.join(", ")}`);
  }
  if (typeof value === "string" && typeof schema.pattern === "string") {
    if (!new RegExp(schema.pattern).test(value)) {
      errors.push(`${path}: ${JSON.stringify(value)} does not match ${schema.pattern}`);
    }
  }
  if (isObject(value)) {
    if (Array.isArray(schema.required)) {
      for (const key of schema.required) {
        if (!(key in value)) errors.push(`${path}: missing required property "${key}"`);
      }
    }
    if (isObject(schema.properties)) {
      for (const [key, sub] of Object.entries(schema.properties)) {
        if (key in value) walk(value[key], sub, `${path}.${key}`, errors);
      }
    }
  }
  if (Array.isArray(value) && isObject(schema.items)) {
    value.forEach((item, index) => walk(item, schema.items, `${path}[${index}]`, errors));
  }
}

const options = parseArgs(process.argv.slice(2));
if (options.help) {
  console.log(USAGE);
  process.exit(0);
}

const root = resolve(options.root);
const siteDir = resolve(options.site ?? join(root, "site"));
const generator = options.generator;

const catalogPath = join(root, "catalog.json");
const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));

const schemaPath = resolve(options.schema ?? join(siteDir, "catalog.schema.json"));
if (!options.noValidate && (options.schema !== undefined || existsSync(schemaPath))) {
  if (!existsSync(schemaPath)) {
    console.error(`schema not found: ${schemaPath}`);
    process.exit(1);
  }
  const errors = [];
  walk(catalog, JSON.parse(readFileSync(schemaPath, "utf8")), "catalog", errors);
  if (errors.length) {
    console.error(`${slash(relative(root, catalogPath))} does not match ${slash(relative(root, schemaPath))}:`);
    for (const error of errors) console.error(`  ${error}`);
    process.exit(1);
  }
}

const css = readFileSync(join(siteDir, "src/room.css"), "utf8");
const js = readFileSync(join(siteDir, "src/room.js"), "utf8");
const svg = readFileSync(join(siteDir, "src/room.svg"), "utf8").trim();

const site = catalog.site || {};
const character = (site.character && site.character.name) || "President";
const objects = catalog.objects || [];

const esc = (s) =>
  String(s == null ? "" : s).replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  }[c]));

const title = (s) => String(s).toUpperCase();
const statusWord = (s) =>
  ({ shipped: "SHIPPED", beta: "BETA", planned: "PLANNED", retired: "RETIRED" }[s] || title(s || "unknown"));

function spots() {
  return objects
    .map((o) => {
      const s = o.spot || { x: 0, y: 0, w: 5, h: 5 };
      return (
        `<button class="spot" type="button" data-object="${esc(o.id)}" aria-expanded="false"` +
        ` aria-label="${esc(o.name)}"` +
        ` style="left:${s.x}%;top:${s.y}%;width:${s.w}%;height:${s.h}%">` +
        `<span class="spot__tag" aria-hidden="true">${esc(title(o.name))}</span></button>`
      );
    })
    .join("\n        ");
}

function row(o, t) {
  return (
    `<li><button class="row" type="button" data-object="${esc(o.id)}" data-tool="${esc(t.id)}">` +
    `<span class="row__id">${esc(t.id)}</span>` +
    `<span class="row__name">${esc(t.name)}${t.sample ? " (sample)" : ""}</span>` +
    `<span class="chip chip--${["shipped", "beta", "planned", "retired"].includes(t.status) ? t.status : "planned"}">${esc(statusWord(t.status))}</span>` +
    `</button></li>`
  );
}

function notebook() {
  return objects
    .map((o) => {
      const rows = (o.tools || []).length
        ? `<ul>${o.tools.map((t) => row(o, t)).join("")}</ul>`
        : o.kind === "chapter"
          ? `<p class="empty">Nothing catalogued here yet.</p>`
          : "";
      return (
        `<div class="chapter"><h3>${esc(title(o.name))}</h3>` +
        `<p class="chapter__line">${esc(o.line)}</p>${rows}</div>`
      );
    })
    .join("\n      ");
}

const html = `<!doctype html>
<!-- GENERATED by ${generator} from catalog.json — edit the source, not this file. -->
<html lang="en" data-motion="on">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(site.title || "The Student Council Room")}</title>
<meta name="description" content="${esc(site.tagline || "A personal room for everything I build.")}">
<meta name="theme-color" content="#060509">
<meta name="color-scheme" content="dark">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<style>
${css}
</style>
</head>
<body>
<a class="skip" href="#room">Skip to the room</a>

<div class="wrap">
  <header class="masthead">
    <h1>${esc(site.title || "The Student Council Room")}</h1>
    <p class="masthead__meta">Edition <b>${esc(site.edition || "—")}</b></p>
    <button class="motion" type="button" data-tool="motion" aria-pressed="true">MOTION ON</button>
  </header>

  <main id="room">
    <div class="frame">
      <div class="stage">
${svg}
      </div>
      <div class="spots">
        ${spots()}
      </div>
      <section class="win" id="win" data-open="false" aria-live="polite">
        <p class="win__name" id="win-name">${esc(title(character))}</p>
        <h2 class="win__title" id="win-title">The room</h2>
        <p class="win__text" id="win-text">Pick something in the room. Or read the notebook below.</p>
        <div id="win-tools"></div>
        <div class="win__acts" id="win-acts"></div>
      </section>
    </div>
  </main>
</div>

<div class="wrap">
  <section class="notebook" id="catalog" aria-labelledby="catalog-h">
    <h2 id="catalog-h">The notebook</h2>
    <p class="notebook__note">Every object in the room, written out — the same catalogue, without the picture.</p>
      ${notebook()}
  </section>

  <footer class="colophon">
    <p>${esc(site.tagline || "")} Built as one static page; no framework, no trackers, no webfont CDN.</p>
    <p>Generated from <code>catalog.json</code> by <code>${generator}</code>. Tokens inherit the estate canon (<code>design/uika-canonical.css</code>, ADR-0011).</p>
  </footer>
</div>

<script type="application/json" id="data">${JSON.stringify(objects)}</script>
<script>window.__ROOM = ${JSON.stringify({ character: title(character), edition: site.edition || "" })};</script>
<script>
${js}
</script>
</body>
</html>
`;

const htmlPath = join(siteDir, "index.html");
const mdPath = join(root, "catalog.md");

const md = [
  `# ${site.title || "The Student Council Room"}`,
  "",
  `_${site.tagline || ""}_ · edition ${site.edition || "—"}`,
  "",
  "Generated from `catalog.json` by `" + generator + "`. The room: see `" + slash(relative(root, htmlPath)) + "`.",
  "",
  ...objects.flatMap((o) => {
    const head = [`## ${o.name}${o.kind === "chapter" ? "" : " (room)"}`, "", `> ${o.line}`, ""];
    const body = (o.tools || []).length
      ? o.tools.map(
          (t) =>
            `- **${t.name}** \`${t.id}\` — ${t.job} _(${t.platform} · ${t.lang} · ${statusWord(t.status)}${t.sample ? " · sample entry" : ""})_`,
        )
      : ["- _Nothing catalogued here yet._"];
    return [...head, ...body, ""];
  }),
].join("\n");

const summary = `${objects.length} objects, ${objects.reduce((n, o) => n + (o.tools || []).length, 0)} tools`;

if (options.check) {
  const stale = [
    [htmlPath, html],
    [mdPath, md],
  ].filter(([path, expected]) => readOrNull(path) !== expected);

  if (stale.length) {
    console.error("stale output — run the builder and commit the result:");
    for (const [path] of stale) console.error(`  ${slash(relative(root, path))}`);
    process.exit(1);
  }
  console.log(`up to date — ${summary}`);
} else {
  writeFileSync(htmlPath, html);
  writeFileSync(mdPath, md);
  console.log(`built ${slash(relative(root, htmlPath))} + ${slash(relative(root, mdPath))} — ${summary}`);
}
